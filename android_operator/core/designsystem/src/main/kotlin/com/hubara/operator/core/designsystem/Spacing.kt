package com.hubara.operator.core.designsystem

import androidx.compose.ui.unit.dp

/**
 * Espaciado en la grilla de 4 dp de Material. `margin` es el margen lateral de las pantallas compactas (16 dp);
 * dentro de una tarjeta se usa `lg` y entre tarjetas `sm`.
 */
object Spacing {
    val xxs = 2.dp
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
    val xxl = 32.dp
    val margin = 16.dp
}
