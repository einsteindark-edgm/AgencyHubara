def specs_payload() -> list[dict[str, object]]:
    """Registro serializable para la API y el dashboard."""
    return [
        {
            "id": c.id,
            "name": c.name,
            "family": c.family,
            "family_label": FAMILIES[c.family][0],
            "stage": FAMILIES[c.family][1],
            "level": c.level,
            "kind": c.kind,
            "applies": c.applies,
            "rule": c.rule,
            "origin": list(c.origin),
            "golden_behaviors": list(c.golden_behaviors),
            "twin_of": c.twin_of,
        }
        for c in CHECKS
    ]
